// Extract mounting measurements from the shipped GLBs. Run after replacing assets.
import fs from 'node:fs'
const root = new URL('../public/assets/models/diamond/', import.meta.url)
const cuts = {}
for (const file of fs.readdirSync(root).filter(name => name.endsWith('.glb'))) {
  const bytes = fs.readFileSync(new URL(file, root))
  const jsonLength = bytes.readUInt32LE(12)
  const gltf = JSON.parse(bytes.subarray(20, 20 + jsonLength).toString())
  const binary = bytes.subarray(28 + jsonLength)
  const primitive = gltf.meshes[0].primitives[0]
  const read = id => {
    const accessor = gltf.accessors[id], view = gltf.bufferViews[accessor.bufferView]
    const offset = (view.byteOffset || 0) + (accessor.byteOffset || 0)
    const components = accessor.type === 'VEC3' ? 3 : 1
    const size = accessor.componentType === 5126 || accessor.componentType === 5125 ? 4 : 2
    return Array.from({ length: accessor.count * components }, (_, i) => {
      const at = offset + i * size
      return accessor.componentType === 5126 ? binary.readFloatLE(at) : size === 4 ? binary.readUInt32LE(at) : binary.readUInt16LE(at)
    })
  }
  const positions = read(primitive.attributes.POSITION), indices = read(primitive.indices)
  let volume = 0
  for (let i = 0; i < indices.length; i += 3) {
    const [a, b, c] = indices.slice(i, i + 3).map(index => positions.slice(index * 3, index * 3 + 3))
    volume += (a[0] * (b[1] * c[2] - b[2] * c[1]) + a[1] * (b[2] * c[0] - b[0] * c[2]) + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6
  }
  const points = Array.from({ length: positions.length / 3 }, (_, i) => positions.slice(i * 3, i * 3 + 3))
  const contour = points.filter(point => Math.abs(point[2] - 0.04) < 0.00001).map(point => point.slice(0, 2))
  cuts[file.replace('.glb', '')] = { volume: Math.abs(volume), width: gltf.accessors[primitive.attributes.POSITION].max[0] - gltf.accessors[primitive.attributes.POSITION].min[0], length: gltf.accessors[primitive.attributes.POSITION].max[1] - gltf.accessors[primitive.attributes.POSITION].min[1], contour }
}
fs.writeFileSync(new URL('../src/data/gemMeasurements.ts', import.meta.url), '// Generated by scripts/measure-gems.mjs from the shipped GLBs. Local +Z faces the table; girdle reference is Z=0.\nexport const gemMeasurements = ' + JSON.stringify(cuts, null, 2) + ' as const\n')
